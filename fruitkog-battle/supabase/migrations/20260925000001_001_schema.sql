on public.profiles(lower(display_name))
where account_type='registered';

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare nick text;
begin
  if new.email is null then
    return new;
  end if;

  nick := left(regexp_replace(trim(coalesce(new.raw_user_meta_data->>'school_nick','')), '\s+', ' ', 'g'), 48);
  if length(nick) < 1 then raise exception 'School nick required'; end if;

  if exists(select 1 from public.profiles where account_type='registered' and lower(display_name)=lower(nick)) then
    raise exception 'School nick already registered';
  end if;

  insert into public.profiles(user_id,display_name,account_type)
  values(new.id,nick,'registered');

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.is_school_nick_available(p_nick text)
returns boolean
language sql
security definer
stable
set search_path=''
as $$
  select not exists(
    select 1 from public.profiles
    where account_type='registered'
      and lower(display_name)=lower(left(regexp_replace(trim(p_nick), '\s+', ' ', 'g'),48))
  );
$$;

create or replace function public.claim_guest_name(p_name text)
returns public.profiles
language plpgsql
security definer
set search_path=''
as $$
declare
  uid uuid:=auth.uid();
  clean_name text:=left(regexp_replace(trim(p_name), '\s+', ' ', 'g'),32);
  p public.profiles%rowtype;
begin
  if uid is null then raise exception 'Authentication required'; end if;
  if length(clean_name)<1 then raise exception 'Guest name required'; end if;

  if exists(select 1 from auth.users where id=uid and email is not null) then
    raise exception 'Guest profile requires anonymous user';
  end if;

  if exists(select 1 from public.profiles where account_type='registered' and lower(display_name)=lower(clean_name)) then
    raise exception 'Guest name conflicts with registered player';
  end if;

  insert into public.profiles(user_id,display_name,account_type)
  values(uid,clean_name,'guest')
  on conflict(user_id) do update set display_name=excluded.display_name
  returning * into p;

  return p;
end;
$$;

create table if not exists public.games (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  game_type text not null default 'casual' check(game_type in ('casual','rated','tournament')),
  visibility text not null default 'public' check(visibility in ('public','private')),
  player1_id uuid not null references auth.users(id) on delete restrict,
  player1_name text not null,
  player2_id uuid references auth.users(id) on delete restrict,
  player2_name text,
  player1_ready boolean not null default false,
  player2_ready boolean not null default false,
  status text not null default 'waiting' check(status in ('waiting','placing','playing','finished','cancelled')),
  current_turn uuid references auth.users(id),
  winner_id uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  finished_at timestamptz,
  constraint games_players_different check(player2_id is null or player2_id<>player1_id)
);

create index if not exists games_lobby_idx on public.games(visibility,status,created_at desc);

create table if not exists public.fleets (
  game_id uuid not null references public.games(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  ships jsonb not null,
  created_at timestamptz not null default now(),
  primary key(game_id,owner_id)
);

create table if not exists public.shots (
  id bigint generated by default as identity primary key,
  game_id uuid not null references public.games(id) on delete cascade,
  shooter_id uuid not null references auth.users(id) on delete cascade,
  target_id uuid not null references auth.users(id) on delete cascade,
  cell text not null,
  result text not null check(result in ('miss','hit','sunk','win')),
  created_at timestamptz not null default now(),
  unique(game_id,shooter_id,cell)
);

create table if not exists public.tournaments (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  status text not null default 'draft' check(status in ('draft','registration','active','finished','cancelled')),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_players (
  tournament_id uuid not null references public.tournaments(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  seed integer,
  status text not null default 'active' check(status in ('active','withdrawn','disqualified')),
  primary key(tournament_id,user_id)
);

create table if not exists public.tournament_matches (
  id uuid primary key default gen_random_uuid(),
  tournament_id uuid not null references public.tournaments(id) on delete cascade,
  round_no integer not null,
  position integer not null,
  player1_id uuid references auth.users(id),
  player2_id uuid references auth.users(id),
  winner_id uuid references auth.users(id),
  game_id uuid references public.games(id),
  status text not null default 'pending' check(status in ('pending','ready','playing','awaiting_confirmation','finished','technical','cancelled')),
  next_match_id uuid references public.tournament_matches(id),
  next_slot smallint check(next_slot in (1,2)),
  created_at timestamptz not null default now(),
  unique(tournament_id,round_no,position)
);

