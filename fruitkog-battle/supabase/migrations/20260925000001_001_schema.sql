create or replace function public.assert_valid_fleet(p_ships jsonb)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  ship_rec record; cell_text text; ship_len int; ship_cells jsonb;
  ship_rows int[]; ship_cols int[];
  all_rows int[]:=array[]::int[]; all_cols int[]:=array[]::int[];
  all_ship_idx int[]:=array[]::int[]; all_cells text[]:=array[]::text[];
  r int;c int;min_r int;max_r int;min_c int;max_c int;i int;j int;
begin
  if jsonb_typeof(p_ships)<>'array' or jsonb_array_length(p_ships)<>10 then raise exception 'Invalid fleet'; end if;

  if (select count(*) from jsonb_array_elements(p_ships) s(value) where (s.value->>'length')::int=4)<>1
  or (select count(*) from jsonb_array_elements(p_ships) s(value) where (s.value->>'length')::int=3)<>2
  or (select count(*) from jsonb_array_elements(p_ships) s(value) where (s.value->>'length')::int=2)<>3
  or (select count(*) from jsonb_array_elements(p_ships) s(value) where (s.value->>'length')::int=1)<>4
  then raise exception 'Invalid fleet'; end if;

  for ship_rec in select value as ship, ordinality::int as ship_idx from jsonb_array_elements(p_ships) with ordinality loop
    ship_len:=(ship_rec.ship->>'length')::int;
    ship_cells:=ship_rec.ship->'cells';
    if ship_cells is null or jsonb_typeof(ship_cells)<>'array' or jsonb_array_length(ship_cells)<>ship_len then raise exception 'Invalid fleet'; end if;

    ship_rows:=array[]::int[]; ship_cols:=array[]::int[];
    for cell_text in select upper(value) from jsonb_array_elements_text(ship_cells) loop
      if cell_text !~ '^[A-J](10|[1-9])$' then raise exception 'Invalid fleet'; end if;
      if cell_text=any(all_cells) then raise exception 'Invalid fleet'; end if;

      c:=ascii(substr(cell_text,1,1))-ascii('A')+1;
      r:=substr(cell_text,2)::int;

      ship_rows:=array_append(ship_rows,r); ship_cols:=array_append(ship_cols,c);
      all_cells:=array_append(all_cells,cell_text); all_rows:=array_append(all_rows,r); all_cols:=array_append(all_cols,c); all_ship_idx:=array_append(all_ship_idx,ship_rec.ship_idx);
    end loop;

    select min(x),max(x) into min_r,max_r from unnest(ship_rows)x;
    select min(x),max(x) into min_c,max_c from unnest(ship_cols)x;

    if not((min_r=max_r and max_c-min_c+1=ship_len) or (min_c=max_c and max_r-min_r+1=ship_len)) then raise exception 'Invalid fleet'; end if;
  end loop;

  if array_length(all_cells,1) is not null then
    for i in 1..array_length(all_cells,1) loop
      if i<array_length(all_cells,1) then
        for j in (i+1)..array_length(all_cells,1) loop
          if all_ship_idx[i]<>all_ship_idx[j] and abs(all_rows[i]-all_rows[j])<=1 and abs(all_cols[i]-all_cols[j])<=1 then
            raise exception 'Invalid fleet';
          end if;
        end loop;
      end if;
    end loop;
  end if;
end;
$$;

create or replace function public.create_game(p_visibility text default 'public')
returns jsonb
language plpgsql security definer set search_path=''
as $$
declare uid uuid:=auth.uid();p public.profiles%rowtype;g public.games%rowtype;new_code text;v text:=lower(trim(p_visibility));
begin
  if uid is null then raise exception 'Authentication required'; end if;
  select * into p from public.profiles where user_id=uid;
  if not found then raise exception 'Profile required'; end if;
  if v not in ('public','private') then v:='public'; end if;
  loop
    new_code:=upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
    exit when not exists(select 1 from public.games where code=new_code);
  end loop;
  insert into public.games(code,game_type,visibility,player1_id,player1_name)
  values(new_code,'casual',v,uid,p.display_name) returning * into g;
  return to_jsonb(g);
end;
$$;

create or replace function public.join_public_game(p_game_id uuid)
returns jsonb
language plpgsql security definer set search_path=''
as $$
declare uid uuid:=auth.uid();p public.profiles%rowtype;g public.games%rowtype;
begin
  if uid is null then raise exception 'Authentication required'; end if;
  select * into p from public.profiles where user_id=uid;
  if not found then raise exception 'Profile required'; end if;
  select * into g from public.games where id=p_game_id for update;
  if not found then raise exception 'Game not found'; end if;
  if g.player1_id=uid then raise exception 'Cannot join your own game'; end if;
  if g.visibility<>'public' or g.status<>'waiting' or g.player2_id is not null then raise exception 'Game is full'; end if;
  update public.games set player2_id=uid,player2_name=p.display_name,status='placing',updated_at=now() where id=g.id returning * into g;
  return to_jsonb(g);
end;
$$;

